package rpcnode.toolkit.chains.aptos.infrastructure

import rpcnode.toolkit.nodes.infrastructure.host.HostSystemdUnitTemplate

/**
 * fullnode.yaml and the systemd unit. Every constant here is the same value as the matching `clientConfig.bindings`
 * literal in `chains/aptos/network.yml`.
 */
object AptosUnitBodies
{
    const val NODE_NOFILE = 1_048_576
    const val API_HOST = "0.0.0.0"
    const val LOOPBACK = "127.0.0.1"
    const val RUNTIME_WORKER_MULTIPLIER = 2
    const val MAX_GAS_VIEW_FUNCTION = 2_000_000L
    const val WAIT_BY_HASH_MAX_ACTIVE = 100
    const val CONTENT_LENGTH_LIMIT = 8_388_608L
    const val TRANSACTION_SUBMISSION_ENABLED = true
    const val MAX_INBOUND = 50
    const val MAX_OUTBOUND = 5
    const val FULLNODE_YAML = "fullnode.yaml"
    const val GENESIS_BLOB = "genesis.blob"
    const val WAYPOINT = "waypoint.txt"
    const val RELATIVE_LOG = "logs/aptos.log"

    /** Keys an operator may override (Node config → Flag overrides) with a validator for the value. */
    private val OVERRIDES: Map<String, (String) -> Boolean> = mapOf(
        "api.runtime_worker_multiplier" to { v -> v.toIntOrNull()?.let { it in 1..64 } == true },
        "api.max_gas_view_function" to { v -> v.toLongOrNull()?.let { it >= 1 } == true },
        "api.wait_by_hash_max_active_connections" to { v -> v.toIntOrNull()?.let { it in 1..100_000 } == true },
        "api.transaction_submission_enabled" to { v -> v == "true" || v == "false" },
        "p2p.max_inbound_connections" to { v -> v.toIntOrNull()?.let { it in 0..10_000 } == true },
        "p2p.max_outbound_connections" to { v -> v.toIntOrNull()?.let { it in 0..10_000 } == true },
    )

    fun execStart(bin: String, yaml: String): String = "$bin -f $yaml"

    fun unit(env: String, nodeDir: String, execStart: String, logFile: String, nofile: Int = NODE_NOFILE): String =
        HostSystemdUnitTemplate.render(
            HostSystemdUnitTemplate.load("aptos", "node.service.tmpl"),
            mapOf(
                "description" to "Aptos fullnode ($env) — RpcNode",
                "node_dir" to nodeDir,
                "exec_start" to execStart,
                "log_file" to logFile,
                "nofile" to nofile.coerceAtLeast(1024).toString(),
            ),
        )

    fun fullnodeYaml(
        env: String,
        stateDir: String,
        genesisPath: String,
        waypointPath: String,
        ports: AptosPorts,
        mode: String,
        overrides: Map<String, String> = emptyMap(),
    ): String
    {
        val valid = overrides.filter { (k, v) -> OVERRIDES[k]?.invoke(v) == true }
        fun value(key: String, default: Any): String = valid[key] ?: default.toString()
        val genesis = AptosBootstrapMode.normalize(mode) == AptosBootstrapMode.GENESIS
        return buildString {
            appendLine("# Generated by toolkit - aptos/${AptosClusters.normalizeEnv(env)}")
            appendLine("base:")
            appendLine("  role: \"full_node\"")
            appendLine("  data_dir: ${quote(stateDir)}")
            appendLine("  waypoint:")
            appendLine("    from_file: ${quote(waypointPath)}")
            appendLine()
            appendLine("execution:")
            appendLine("  genesis_file_location: ${quote(genesisPath)}")
            appendLine()
            appendLine("api:")
            appendLine("  enabled: true")
            appendLine("  address: ${quote("$API_HOST:${ports.http}")}")
            appendLine("  runtime_worker_multiplier: ${value("api.runtime_worker_multiplier", RUNTIME_WORKER_MULTIPLIER)}")
            appendLine("  max_gas_view_function: ${value("api.max_gas_view_function", MAX_GAS_VIEW_FUNCTION)}")
            appendLine("  wait_by_hash_max_active_connections: ${value("api.wait_by_hash_max_active_connections", WAIT_BY_HASH_MAX_ACTIVE)}")
            appendLine("  content_length_limit: $CONTENT_LENGTH_LIMIT")
            appendLine("  transaction_submission_enabled: ${value("api.transaction_submission_enabled", TRANSACTION_SUBMISSION_ENABLED)}")
            appendLine()
            appendLine("full_node_networks:")
            appendLine("  - network_id: \"public\"")
            appendLine("    discovery_method: \"onchain\"")
            appendLine("    listen_address: ${quote("/ip4/0.0.0.0/tcp/${ports.p2p}")}")
            appendLine("    max_inbound_connections: ${value("p2p.max_inbound_connections", MAX_INBOUND)}")
            appendLine("    max_outbound_connections: ${value("p2p.max_outbound_connections", MAX_OUTBOUND)}")
            appendLine()
            appendLine("inspection_service:")
            appendLine("  address: ${quote(LOOPBACK)}")
            appendLine("  port: ${ports.metrics}")
            appendLine()
            appendLine("admin_service:")
            appendLine("  enabled: false")
            appendLine("  address: ${quote(LOOPBACK)}")
            appendLine("  port: ${ports.admin}")
            appendLine()
            appendLine("state_sync:")
            appendLine("  state_sync_driver:")
            appendLine("    bootstrapping_mode: ${if (genesis) "ExecuteOrApplyFromGenesis" else "DownloadLatestStates"}")
            appendLine("    continuous_syncing_mode: ExecuteTransactionsOrApplyOutputs")
            appendLine()
            appendLine("storage:")
            appendLine("  backup_service_address: ${quote("$LOOPBACK:${ports.backup}")}")
            if (genesis)
            {
                appendLine("  storage_pruner_config:")
                appendLine("    ledger_pruner_config:")
                appendLine("      enable: false")
                appendLine("    state_merkle_pruner_config:")
                appendLine("      enable: false")
                appendLine("    epoch_snapshot_pruner_config:")
                appendLine("      enable: false")
            }
        }
    }

    private fun quote(raw: String): String = "\"" + raw.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
}
