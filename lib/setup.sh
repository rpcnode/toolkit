# Ports: RPC per env 8090/8091/8092; panel default 8093 (bumps only if busy)
TRON_ENV=${TRON_ENV}
TRON_TAG=${TRON_TAG}

TRON_OPT=${TRON_OPT}
TRON_ETC=${TRON_ETC}
TRON_DATA=${TRON_DATA}
TRON_OUTPUT=${TRON_OUTPUT}

TRON_NODE_HTTP_HOST=${TRON_NODE_HTTP_HOST}
TRON_NODE_HTTP_PORT=${TRON_NODE_HTTP_PORT}
TRON_GATEWAY_LISTEN=${TRON_GATEWAY_LISTEN}
