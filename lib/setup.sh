#!/usr/bin/env bash
# Interactive / non-interactive installer for EXISTING (or fresh) TRON nodes.
# Never destroys chain DB by default.

# Interactive port conflict resolver.
# Sets globals: SETUP_RESOLVED_GW_PORT, SETUP_RESOLVED_PANEL_PORT, SETUP_RESOLVED_HTTP_PORT
_setup_resolve_ports() {
  local gw_port="$1" http_port="$2" panel_port="${3:-}" alt yn new_port
  SETUP_RESOLVED_GW_PORT="$gw_port"
  SETUP_RESOLVED_HTTP_PORT="$http_port"
  SETUP_RESOLVED_PANEL_PORT="${panel_port:-${TRON_PANEL_PORT:-}}"

  if port_is_busy "$SETUP_RESOLVED_GW_PORT"; then
    alt="$(suggest_free_port "$SETUP_RESOLVED_GW_PORT")"
    warn "RPC public port ${SETUP_RESOLVED_GW_PORT} is BUSY"
    info "suggestion: use ${alt} (or free the port: ss -lntp | grep :${SETUP_RESOLVED_GW_PORT})"
    if [[ "${SETUP_NONINTERACTIVE:-0}" == "1" ]]; then
      if [[ "${SETUP_STRICT_PREFLIGHT:-0}" == "1" ]]; then
        die "port ${SETUP_RESOLVED_GW_PORT} busy — pass --gateway-port ${alt} or free it"
      fi
      warn "non-interactive: switching RPC port ${SETUP_RESOLVED_GW_PORT} → ${alt}"
      SETUP_RESOLVED_GW_PORT="$alt"
    else
      yn="y"
      _setup_yn "Use free port ${alt} instead of ${SETUP_RESOLVED_GW_PORT}?" "y" yn
      if [[ "$yn" == "y" ]]; then
        SETUP_RESOLVED_GW_PORT="$alt"
      else
        _setup_ask "Enter different RPC public port" "$alt" new_port
        SETUP_RESOLVED_GW_PORT="$new_port"
        if port_is_busy "$SETUP_RESOLVED_GW_PORT"; then
          die "port ${SETUP_RESOLVED_GW_PORT} still busy — aborting"
        fi
      fi
    fi
  else
    ok "RPC public port ${SETUP_RESOLVED_GW_PORT} is free"
  fi

  if [[ -n "${SETUP_RESOLVED_PANEL_PORT}" ]]; then
    if port_is_busy "$SETUP_RESOLVED_PANEL_PORT"; then
      alt="$(suggest_free_port "$SETUP_RESOLVED_PANEL_PORT")"
      warn "Panel port ${SETUP_RESOLVED_PANEL_PORT} is BUSY"
      if [[ "${SETUP_NONINTERACTIVE:-0}" == "1" ]]; then
        warn "non-interactive: switching panel port ${SETUP_RESOLVED_PANEL_PORT} → ${alt}"
        SETUP_RESOLVED_PANEL_PORT="$alt"
      else
        yn="y"
        _setup_yn "Use free panel port ${alt} instead of ${SETUP_RESOLVED_PANEL_PORT}?" "y" yn
        if [[ "$yn" == "y" ]]; then
          SETUP_RESOLVED_PANEL_PORT="$alt"
        else
          _setup_ask "Enter different panel port" "$alt" new_port
          SETUP_RESOLVED_PANEL_PORT="$new_port"
        fi
      fi
    else
      ok "Panel port ${SETUP_RESOLVED_PANEL_PORT} is free"
    fi
  fi

  if port_is_busy "$SETUP_RESOLVED_HTTP_PORT"; then
    alt="$(suggest_free_port "$SETUP_RESOLVED_HTTP_PORT")"
    warn "java-tron HTTP port ${SETUP_RESOLVED_HTTP_PORT} is BUSY"
    info "suggestion: use ${alt} (or point at the existing node with --node-http-port)"
    if [[ "${SETUP_NONINTERACTIVE:-0}" == "1" ]]; then
      if [[ "${SETUP_STRICT_PREFLIGHT:-0}" == "1" ]]; then
        die "port ${SETUP_RESOLVED_HTTP_PORT} busy — pass --node-http-port ${alt}"
      fi
      warn "non-interactive: keeping node HTTP ${SETUP_RESOLVED_HTTP_PORT} (likely existing java-tron)"
    else
      yn="y"
      _setup_yn "Node port ${SETUP_RESOLVED_HTTP_PORT} busy (existing java-tron?). Keep it?" "y" yn
      if [[ "$yn" != "y" ]]; then
        _setup_ask "Enter java-tron HTTP port" "$alt" new_port
        SETUP_RESOLVED_HTTP_PORT="$new_port"
      fi
    fi
  else
    ok "java-tron HTTP port ${SETUP_RESOLVED_HTTP_PORT} is free"
  fi
}

# Prompt helper: SETUP_YES / flags short-circuit.
_setup_ask() {
  local prompt="$1" default="$2" var="$3" reply
  if [[ "${SETUP_NONINTERACTIVE:-0}" == "1" ]]; then
    printf -v "$var" '%s' "$default"
    return 0
  fi
  if [[ ! -t 0 ]]; then
    printf -v "$var" '%s' "$default"
    return 0
  fi
  read -r -p "$prompt [$default]: " reply || true
  if [[ -z "$reply" ]]; then
    printf -v "$var" '%s' "$default"
  else
    printf -v "$var" '%s' "$reply"
  fi
}

_setup_yn() {
  local prompt="$1" default="$2" var="$3" reply
  if [[ "${SETUP_NONINTERACTIVE:-0}" == "1" ]]; then
    printf -v "$var" '%s' "$default"
    return 0
  fi
  if [[ ! -t 0 ]]; then
    printf -v "$var" '%s' "$default"
    return 0
  fi
  read -r -p "$prompt [y/N]: " reply || true
  case "${reply:-$default}" in
    y|Y|yes|YES) printf -v "$var" '%s' "y" ;;
    *) printf -v "$var" '%s' "n" ;;
  esac
}

